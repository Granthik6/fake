export function statusClass(v) {
  const s = String(v || '').toLowerCase();
  if (s.includes('unpaid') || s.includes('unavailable')) return 'blocked';
  if (s.includes('active') || s.includes('approved') || s.includes('completed') || s.includes('transit') || s.includes('paid') || s.includes('delivered') || s.includes('available')) return 'active';
  if (s.includes('pending') || s.includes('review') || s.includes('queue')) return 'pending';
  return 'blocked';
}
